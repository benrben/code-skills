"""The HTML quality report: one self-contained page for the ten generic gates.

The page is for people. Agents read the terminal report and the state file.
Every value from the run is escaped; the page loads nothing from the network.
"""

from __future__ import annotations

import dataclasses
import html
from collections.abc import Sequence

from gate_types import BLOCKED, FAIL, NOT_APPLICABLE, PASS, GateItem, plural
from quality_model import GateRun

MAX_ITEMS_PER_GATE = 200

STATUS_LABELS = {
    PASS: "PASS",
    FAIL: "FAIL",
    BLOCKED: "BLOCKED",
    NOT_APPLICABLE: "N/A",
    "off": "OFF",
    "skipped": "SKIPPED",
    "deferred": "DEFERRED",
}


@dataclasses.dataclass(frozen=True)
class ReportContext:
    repository: str
    scope: str
    generated_at: str
    verdict: str
    command: str = ""
    notes: Sequence[str] = ()


def render_report(context: ReportContext, rows: Sequence[GateRun]) -> str:
    """The complete HTML page."""
    body = "\n".join(
        [
            _header(context, rows),
            _overview(rows),
            '<section class="checks" aria-label="Gates">',
            *(_gate_row(index, row) for index, row in enumerate(rows, 1)),
            "</section>",
            _notes(context.notes),
            "<footer>Generated by code-discipline.</footer>",
        ]
    )
    title = f"Quality report: {context.verdict}"
    return (
        '<!doctype html>\n<html lang="en">\n<head>\n'
        '<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        f"<title>{_e(title)}</title>\n<style>{STYLES}</style>\n</head>\n"
        f"<body>\n<main>\n{body}\n</main>\n</body>\n</html>\n"
    )


def _header(context: ReportContext, rows: Sequence[GateRun]) -> str:
    verdict_class = "pass" if context.verdict == PASS.upper() else "fail"
    command = (
        f'<p class="command"><code>{_e(context.command)}</code></p>'
        if context.command
        else ""
    )
    return (
        f'<header class="hero {verdict_class}">'
        f'<p class="eyebrow">Quality report · {_e(context.scope)}</p>'
        f"<h1>{_e(context.verdict)}</h1>"
        f"<p>{_e(_verdict_sentence(rows))}</p>"
        f'<p class="meta">{_e(context.repository)} · {_e(context.generated_at)}</p>'
        f"{command}</header>"
    )


def _verdict_sentence(rows: Sequence[GateRun]) -> str:
    counts = _status_counts(rows)
    parts = [
        f"{counts[status]} {STATUS_LABELS[status]}"
        for status in STATUS_LABELS
        if counts.get(status)
    ]
    return f"{len(rows)} gates: " + ", ".join(parts) + "."


def _status_counts(rows: Sequence[GateRun]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for row in rows:
        counts[row.status] = counts.get(row.status, 0) + 1
    return counts


def _overview(rows: Sequence[GateRun]) -> str:
    tiles = "".join(
        f'<a class="tile {_css(row.status)}" href="#gate-{_e(row.key)}">'
        f"<span>{_e(row.title)}</span>"
        f"<strong>{_e(STATUS_LABELS.get(row.status, row.status.upper()))}</strong>"
        f"<small>{_e(_headline(row))}</small></a>"
        for row in rows
    )
    return f'<nav class="overview" aria-label="Gate overview">{tiles}</nav>'


def _headline(outcome: GateRun) -> str:
    """A short number for the tile: issues, or the main measurement."""
    measurements = outcome.measurements
    coverage = measurements.get("line_coverage_percent")
    if isinstance(coverage, (int, float)):
        return f"{coverage:g}% of lines"
    executed = measurements.get("executed")
    if isinstance(executed, int):
        return plural(executed, "test") + " ran"
    if outcome.items:
        noun = "issue" if len(outcome.items) == 1 else "issues"
        return f"{len(outcome.items)} {noun}"
    return "no issues" if outcome.status == PASS else ""


def _gate_row(index: int, row: GateRun) -> str:
    outcome = row
    failed = row.status in (FAIL, BLOCKED)
    opened = " open" if failed else ""
    seconds = f" · {row.seconds:.1f}s" if row.seconds is not None else ""
    body = (
        f'<p class="result">{NOT_PASSED}</p>'
        f"{_items_table(outcome.items)}{_details(outcome)}"
        if failed
        else f'<p class="result">{_e(outcome.summary)}</p>'
    )
    return (
        f'<details class="gate {_css(row.status)}" id="gate-{_e(outcome.key)}"'
        f"{opened}><summary>"
        f'<span class="step">{index}</span>'
        f'<span class="name"><strong>{_e(outcome.title)}</strong>'
        f"<small>{_e(outcome.summary)}</small></span>"
        f'<span class="status">{_e(STATUS_LABELS.get(row.status, row.status))}'
        f"{_e(seconds)}</span></summary>"
        f'<div class="gate-body">{body}</div></details>'
    )


NOT_PASSED = "Not passed. Please fix the following:"


def _items_table(items: Sequence[GateItem]) -> str:
    if not items:
        return ""
    shown = items[:MAX_ITEMS_PER_GATE]
    rows = "".join(
        "<tr>"
        f"<td><code>{_e(item.location())}</code></td>"
        f"<td>{_e(item.name)}</td>"
        f"<td>{_e(item.metric)}</td>"
        f'<td class="num">{_e(item.value)}</td>'
        f'<td class="num">{_e(item.limit)}</td>'
        "</tr>"
        for item in shown
    )
    more = (
        f'<p class="more">{len(items) - len(shown)} more issues are in the '
        "state file.</p>"
        if len(items) > len(shown)
        else ""
    )
    return (
        f'<h3>Issues ({len(items)})</h3><div class="table-wrap"><table>'
        "<thead><tr><th>Where</th><th>Name</th><th>Issue</th><th>Value</th>"
        f"<th>Limit</th></tr></thead><tbody>{rows}</tbody>"
        f"</table></div>{more}"
    )


def _details(outcome: GateRun) -> str:
    """Detail lines that are not already shown as findings."""
    described = {item.describe() for item in outcome.items}
    lines = [line for line in outcome.details if line not in described]
    if not lines:
        return ""
    text = "\n".join(lines[:MAX_ITEMS_PER_GATE])
    return f"<pre>{_e(text)}</pre>"


def _notes(notes: Sequence[str]) -> str:
    if not notes:
        return ""
    entries = "".join(f"<li>{_e(note)}</li>" for note in notes)
    return f'<section class="notes"><h2>Notes</h2><ul>{entries}</ul></section>'


def _css(status: str) -> str:
    return "na" if status == NOT_APPLICABLE else status


def _e(value: object) -> str:
    return html.escape(str(value), quote=True)


